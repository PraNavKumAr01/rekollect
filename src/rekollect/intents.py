INTENTS = [(re.compile(p, re.IGNORECASE), d) for p, d in _RAW]


def describe(cmd: str) -> list[str]:
    out: list[str] = []
    for pat, desc in INTENTS:
        if desc not in out and pat.search(cmd):
            out.append(desc)
    return out[:4]